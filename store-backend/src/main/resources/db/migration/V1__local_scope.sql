-- Incremento multi-local sobre el esquema legado que Hibernate ya creó.
CREATE TABLE IF NOT EXISTS locals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO locals (code, name, active)
VALUES ('LOCAL-001', 'Local inicial', TRUE)
ON CONFLICT (code) DO NOTHING;

ALTER TABLE users ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE cash_register ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE cash_inflows ADD COLUMN IF NOT EXISTS local_id BIGINT;
ALTER TABLE cash_outflows ADD COLUMN IF NOT EXISTS local_id BIGINT;

-- SUPERADMIN no tiene local asignado; selecciona un contexto operativo por petición.
UPDATE users u SET local_id = l.id
FROM locals l LEFT JOIN roles r ON r.name = 'SUPERADMIN'
WHERE l.code = 'LOCAL-001' AND u.local_id IS NULL
  AND (u.role_id IS DISTINCT FROM r.id);
UPDATE categories SET local_id = (SELECT id FROM locals WHERE code = 'LOCAL-001') WHERE local_id IS NULL;
UPDATE products SET local_id = (SELECT id FROM locals WHERE code = 'LOCAL-001') WHERE local_id IS NULL;
UPDATE orders SET local_id = (SELECT id FROM locals WHERE code = 'LOCAL-001') WHERE local_id IS NULL;
UPDATE cash_register SET local_id = (SELECT id FROM locals WHERE code = 'LOCAL-001') WHERE local_id IS NULL;
UPDATE cash_inflows ci SET local_id = o.local_id FROM orders o
WHERE ci.order_id = o.id AND ci.local_id IS NULL;
UPDATE cash_outflows co SET local_id = o.local_id FROM orders o
WHERE co.order_id = o.id AND co.local_id IS NULL;
UPDATE cash_outflows co SET local_id = cr.local_id FROM cash_openings op
JOIN cash_register cr ON cr.id = op.cash_register_id
WHERE co.cash_session_id = op.id AND co.local_id IS NULL;
UPDATE cash_outflows SET local_id = (SELECT id FROM locals WHERE code = 'LOCAL-001') WHERE local_id IS NULL;

-- Detener la migración si el historial tiene relaciones inconsistentes.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM users u LEFT JOIN roles r ON r.id = u.role_id
             WHERE u.local_id IS NULL AND COALESCE(r.name, '') <> 'SUPERADMIN')
     OR EXISTS (SELECT 1 FROM categories WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM products WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM orders WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM cash_register WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM cash_inflows WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM cash_outflows WHERE local_id IS NULL)
     OR EXISTS (SELECT 1 FROM products p JOIN categories c ON c.id = p.category_id
                WHERE p.local_id <> c.local_id)
     OR EXISTS (SELECT 1 FROM orders o JOIN users u ON u.id = o.user_id
                WHERE u.local_id IS NOT NULL AND o.local_id <> u.local_id)
     OR EXISTS (SELECT 1 FROM orders o JOIN cash_register cr ON cr.id = o.cash_register_id
                WHERE o.local_id <> cr.local_id)
     OR EXISTS (SELECT 1 FROM order_items oi JOIN orders o ON o.id = oi.order_id
                JOIN product_variants pv ON pv.id = oi.product_variant_id
                JOIN products p ON p.id = pv.product_id WHERE o.local_id <> p.local_id)
     OR EXISTS (SELECT 1 FROM cash_inflows ci JOIN orders o ON o.id = ci.order_id
                WHERE ci.local_id <> o.local_id)
     OR EXISTS (SELECT 1 FROM cash_outflows co JOIN orders o ON o.id = co.order_id
                WHERE co.local_id <> o.local_id)
  THEN
    RAISE EXCEPTION 'Historial multi-local inconsistente; revise los datos antes de continuar';
  END IF;
END $$;

